def align_H_to_baseline(
    H_df,
    baseline_df,
    pad_len
):
    """
    Align H_df to baseline_df.

    baseline.index contains zero-padded GEOID strings.
    POI IDs are converted only to strings and are not padded.
    """

    H = H_df.copy()

    H.index = H.index.map(
        lambda x:
        str(x)
    )

    H.columns = H.columns.map(
        lambda x:
        str(x)
    )


    # --------------------------------------------------------
    # Direct string matching
    # --------------------------------------------------------

    H_try = H.reindex(
        index=baseline_df.index,
        columns=baseline_df.columns
    )

    if H_try.notna().values.any():

        H_aligned = (
            H_try.fillna(0)
        )

        print(
            'align_H_to_baseline: '
            'direct string match found, '
            f'nonzero sum = '
            f'{H_aligned.values.sum():.4f}'
        )

        return H_aligned


    # --------------------------------------------------------
    # If pandas removed GEOID leading zeros,
    # restore them using the shapefile-derived pad length.
    # --------------------------------------------------------

    H.index = H.index.map(
        lambda x:
        str(x).zfill(pad_len)
    )

    H_try = H.reindex(
        index=baseline_df.index,
        columns=baseline_df.columns
    )

    if H_try.notna().values.any():

        H_aligned = (
            H_try.fillna(0)
        )

        print(
            'align_H_to_baseline: '
            'zero-padded string match found, '
            f'nonzero sum = '
            f'{H_aligned.values.sum():.4f}'
        )

        return H_aligned


    raise ValueError(
        'Cannot align '
        'figure4b_reference_flow.csv '
        'to figure4b_baseline_flow.csv.'
    )


