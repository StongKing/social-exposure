# 控制绘制密度
max_edges = 40000


def cap_edges(
    edges
):

    if len(edges) == 0:

        return edges

    edges = sorted(
        edges,
        key=lambda x:
        x[2],
        reverse=True
    )

    return edges[
        :
        min(
            len(edges),
            max_edges
        )
    ]


