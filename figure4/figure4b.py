def get_present_lists(
    df_ref,
    df_other
):
    idx = [
        str(x)
        for x in df_ref.index
    ]

    cols = [
        str(x)
        for x in df_ref.columns
    ]

    idx_present = [
        c
        for c in idx
        if (
            c in df_ref.index
            and
            c in df_other.index
        )
    ]

    cols_present = [
        p
        for p in cols
        if (
            p in df_ref.columns
            and
            p in df_other.columns
        )
    ]

    return (
        idx_present,
        cols_present
    )


